"""Write the paper's results tables from the paper data.

    python3 tables/make_tables.py ../results/paper_v8.json      (run from paper/ in the public repository)

The JSON comes from `python3 harness/paper_data.py v8 > results/paper_v8.json` in the main checkout: pass 1 only,
provider refusals scored 0, 95% bootstrap CIs over cells. Writes tables/main_results.tex, tables/skill_breakdown.tex
and tables/per_class.tex. The Claude models are reported at effort high;
Qwen3.8-27B is reported with thinking on and off.
"""
import json
import statistics
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent
# (solver id, display name, setting); closed models first, then open weights, each by Index
AGENTS = [
    ("gpt-6.1-sol", "GPT-6.1 Sol", "high"),
    ("claude-opus-5-5-high", "Claude Opus 5.5", "high"),
    ("claude-sonnet-5-5-high", "Claude Sonnet 5.5", "high"),
    ("gpt-6.1-terra", "GPT-6.1 Terra", "high"),
    ("claude-haiku-5-5-high", "Claude Haiku 5.5", "high"),
    ("gpt-6-luna", "GPT-6 Luna", "high"),
    ("qwen3.8-27b", "Qwen3.8-27B", "thinking"),
    ("minimax-m2.7", "MiniMax-M2.7", "thinking"),
    ("deepseek-v4-flash", "DeepSeek-V4-Flash", "thinking, high"),
    ("inkling-2-mini", "Inkling 2 Mini", "thinking, high"),
    ("qwen3.8-27b-nothink", "Qwen3.8-27B", "no thinking"),
]
OPEN = {"qwen3.8-27b", "qwen3.8-27b-nothink", "minimax-m2.7", "deepseek-v4-flash", "inkling-2-mini"}
SHORT = {"gpt-6.1-sol": "Sol", "claude-opus-5-5-high": "Opus", "claude-sonnet-5-5-high": "Sonnet",
         "gpt-6.1-terra": "Terra", "claude-haiku-5-5-high": "Haiku", "gpt-6-luna": "Luna", "qwen3.8-27b": "Qwen-T", "qwen3.8-27b-nothink": "Qwen-N",
         "minimax-m2.7": "MiniMax", "deepseek-v4-flash": "DeepSeek", "inkling-2-mini": "Inkling"}


def bold_max(vals, fmt="{:.1f}"):
    best = max(v for v in vals if v is not None)
    return [("--" if v is None else (r"\textbf{" + fmt.format(v) + "}" if fmt.format(v) == fmt.format(best)
                                     else fmt.format(v))) for v in vals]


def main(path):
    d = json.loads(Path(path).read_text())
    M = {m["id"]: m for m in d["models"]}
    for s, _, _ in AGENTS:
        assert M[s]["complete"], s
    ms = [M[s] for s, _, _ in AGENTS]
    cells = {f"{c['item']}|{c['level']}": c for c in d["cells"]}

    # main table
    idx = bold_max([m["index"] for m in ms])
    fam = {g: bold_max([m["sub"][g]["index"] for m in ms]) for g in ("read", "edit", "skill")}
    solved = bold_max([m["solved"] for m in ms], "{:d}")
    rows = []
    for k, ((s, name, setting), m) in enumerate(zip(AGENTS, ms)):
        if k and s in OPEN and AGENTS[k - 1][0] not in OPEN:
            rows.append(r"\midrule")
            rows.append(r"\multicolumn{8}{@{}l}{\textit{Open weights}} \\")
        cost = "--" if m["cost_per_task"] is None else f"{m['cost_per_task']:.2f}"
        ci = f"[{m['ci'][0]:.1f}, {m['ci'][1]:.1f}]"
        rows.append(f"{name} & {setting} & {idx[k]} {{\\scriptsize {ci}}} & {fam['read'][k]} & {fam['edit'][k]} & "
                    f"{fam['skill'][k]} & {solved[k]} & {cost} \\\\")
    n = {g: ms[0]["sub"][g]["coverage"] for g in ("read", "edit", "skill")}
    (OUT / "main_results.tex").write_text("\n".join([
        f"% Generated by tables/make_tables.py from paper_v8.json (built {d['built']}). Do not edit by hand.",
        r"\begin{tabular}{@{}llr rrr rr@{}}",
        r"\toprule",
        rf"Agent & Setting & Index {{\scriptsize [95\% CI]}} & Read & Edit & Skill & Solved & \$/task \\",
        rf" & & {{\scriptsize {d['core_cells']} cells}} & {{\scriptsize {n['read']}}} & {{\scriptsize {n['edit']}}} "
        rf"& {{\scriptsize {n['skill']}}} & & \\",
        r"\midrule",
        r"\multicolumn{8}{@{}l}{\textit{Closed}} \\",
        *rows,
        r"\bottomrule",
        r"\end{tabular}", ""]))

    # skill breakdown
    groups = [
        ("General skills", lambda c: c["skill_group"] == "general" and c["variant"] == "main"),
        ("Whole programs", lambda c: c["skill_group"] == "whole programs"),
        ("Function completion", lambda c: c["skill_group"] == "function completion"),
        ("HumanEval functions", lambda c: c["skill_group"] == "HumanEval functions"),
        (r"\addlinespace Hand design", lambda c: c["variant"] == "hand"),
        ("One-step", lambda c: c["variant"] == "onestep"),
        ("Search", lambda c: c["variant"] == "search"),
        ("Worked examples", lambda c: c["variant"] == "examples"),
        ("Second model", lambda c: c["variant"] == "donor"),
    ]
    rows = []
    for label, f in groups:
        ks = [k for k, c in cells.items() if c["group"] == "skill" and f(c)]
        vals = [statistics.mean(m["scores"][k][0] for k in ks) for m in ms]
        rows.append(f"{label} ({len(ks)}) & " + " & ".join(bold_max(vals)) + r" \\")
    head = " & ".join(SHORT[s] for s, _, _ in AGENTS)
    (OUT / "skill_breakdown.tex").write_text("\n".join([
        f"% Generated by tables/make_tables.py from paper_v8.json (built {d['built']}). Do not edit by hand.",
        r"\begin{tabular}{@{}l" + "r" * len(AGENTS) + "@{}}",
        r"\toprule",
        f"Skill tasks (cells) & {head} \\\\",
        r"\midrule",
        r"\multicolumn{" + str(len(AGENTS) + 1) + r"}{@{}l}{\textit{Main tasks}} \\",
        *rows[:4],
        r"\midrule",
        r"\multicolumn{" + str(len(AGENTS) + 1) + r"}{@{}l}{\textit{Variants}} \\",
        *[r.replace(r"\addlinespace ", "") for r in rows[4:]],
        r"\bottomrule",
        r"\end{tabular}", ""]))

    # per class
    rows = []
    for fam_name, g in (("Read", "read"), ("Edit", "edit"), ("Skill", "skill")):
        rows.append(r"\multicolumn{" + str(len(AGENTS) + 1) + r"}{@{}l}{\textit{" + fam_name + r"}} \\")
        for k in d["groups"][g]:
            nk = sum(c["class"] == k for c in d["cells"])
            vals = [m["per_class"][k] for m in ms]
            rows.append(f"{k} ({nk}) & " + " & ".join(bold_max(vals)) + r" \\")
        rows.append(r"\midrule")
    (OUT / "per_class.tex").write_text("\n".join([
        f"% Generated by tables/make_tables.py from paper_v8.json (built {d['built']}). Do not edit by hand.",
        r"\begin{tabular}{@{}l" + "r" * len(AGENTS) + "@{}}",
        r"\toprule",
        f"Class (cells) & {head} \\\\",
        r"\midrule",
        *rows[:-1],
        r"\bottomrule",
        r"\end{tabular}", ""]))
    print("wrote", ", ".join(p.name for p in sorted(OUT.glob("*.tex"))))


if __name__ == "__main__":
    main(sys.argv[1])
